import assert from 'node:assert/strict'
import { chromium, expect } from '@playwright/test'
import pg from 'pg'
import argon2 from 'argon2'

const pool = new pg.Pool({ connectionString: 'postgresql://postgres:local-preview-only@127.0.0.1:55432/postgres' })
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true })
let userId
try {
  const email = `faculty-programme-${Date.now()}@local.test`
  userId = (await pool.query('INSERT INTO users(email,display_name,password_hash,created_at) VALUES($1,$2,$3,$4) RETURNING id', [email, 'Test programme', await argon2.hash('Programme-Local-2026!'), new Date().toISOString()])).rows[0].id
  await pool.query("INSERT INTO academic_profiles(user_id,year_code,faculty_id,legacy_exempt,completed_at) VALUES($1,'Y4','bordeaux',FALSE,NOW())", [userId])
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = []
  let profileWrites = 0
  page.on('request', request => { if (request.url().includes('/api/onboarding/profile') && request.method() === 'PATCH') profileWrites++ })
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:5173/itemstracker/onboarding-preview.html')
  await page.getByRole('textbox', { name: 'Adresse e-mail' }).fill(email)
  await page.getByRole('textbox', { name: 'Mot de passe' }).fill('Programme-Local-2026!')
  await page.getByRole('button', { name: 'Se connecter', exact: true }).click()
  const navigateItems = async () => { await page.locator('.sidebar-nav-item').filter({ hasText: 'Items' }).click(); await page.getByRole('button', { name: 'Locales', exact: true }).click() }
  await navigateItems()
  const programme = page.locator('.faculty-resources')
  await expect(programme).toContainText('Bordeaux · 4e année · 2026–2027')
  await expect(programme.locator('.faculty-unit')).toHaveCount(21)
  await programme.locator('.faculty-unit>summary').first().click()
  await expect(programme.getByRole('link', { name: /Document de la faculté|Consulter la source|Source du lien/ })).toHaveCount(0)
  await page.screenshot({ path: '/tmp/itemstracker-user-faculty-programme-desktop.png', fullPage: false })
  await programme.getByRole('button', { name: 'Item #9', exact: true }).first().click()
  await expect(page.locator('.item-detail-hero h2')).toHaveText('Item #9')
  await expect(page.locator('.faculty-item-resources')).toBeVisible()
  await expect(page.locator('.faculty-item-resources')).toContainText('Appareil locomoteur')
  await expect(page.locator('.faculty-item-resources a')).toHaveCount(0)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'Retour aux items', exact: true }).click()
  await page.getByRole('button', { name: 'Locales', exact: true }).click()
  await programme.locator('.faculty-unit>summary').first().click()
  for (const width of [360, 390, 430, 768, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `Local programme overflow at ${width}px`)
  }
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: '/tmp/itemstracker-user-faculty-programme-mobile.png', fullPage: false })
  await page.evaluate(() => { document.documentElement.dataset.theme = 'dark' })
  await page.waitForTimeout(250)
  await page.screenshot({ path: '/tmp/itemstracker-user-faculty-programme-mobile-dark.png', fullPage: false })
  await page.evaluate(() => { document.documentElement.dataset.theme = 'light' })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.locator('.sidebar-profile-trigger').click()
  const settingsCard = page.locator('.academic-settings-card')
  await settingsCard.scrollIntoViewIfNeeded()
  assert.ok(await settingsCard.evaluate(el => el.getBoundingClientRect().height) < 120, 'Locked summary stays compact')
  await expect(settingsCard).toContainText('4e année · Bordeaux')
  await page.screenshot({ path: '/tmp/itemstracker-settings-path-locked-desktop.png' })
  await page.setViewportSize({ width: 390, height: 844 })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  await settingsCard.scrollIntoViewIfNeeded()
  await page.screenshot({ path: '/tmp/itemstracker-settings-path-locked-mobile.png' })
  await page.getByRole('button', { name: 'Modifier mon parcours', exact: true }).click()
  await page.getByLabel('5e année').check()
  const facultyCombo = settingsCard.getByRole('combobox')
  await facultyCombo.fill('Dijon')
  const facultyOptions = page.getByRole('listbox', { name: 'Facultés proposées' })
  await expect(facultyOptions).toBeVisible()
  const lightBackground = await facultyOptions.evaluate(el => getComputedStyle(el).backgroundColor)
  assert.equal(lightBackground, 'rgb(255, 255, 255)', 'Settings faculty dropdown has an opaque light background')
  assert.equal(await facultyCombo.evaluate(el => getComputedStyle(el).boxShadow), 'none', 'Only the outer combobox shows the focus ring')
  await page.screenshot({ path: '/tmp/itemstracker-settings-faculty-dropdown-light.png' })
  await page.evaluate(() => { document.documentElement.dataset.theme = 'dark' })
  const darkBackground = await facultyOptions.evaluate(el => getComputedStyle(el).backgroundColor)
  assert.notEqual(darkBackground, lightBackground)
  assert.notEqual(darkBackground, 'rgba(0, 0, 0, 0)', 'Settings faculty dropdown has an opaque dark background')
  await page.screenshot({ path: '/tmp/itemstracker-settings-faculty-dropdown-dark.png' })
  await page.evaluate(() => { document.documentElement.dataset.theme = 'light' })
  await page.getByRole('button', { name: 'Annuler', exact: true }).click()
  await expect(settingsCard.locator('.academic-form')).toHaveCount(0)
  await expect(settingsCard).toContainText('4e année · Bordeaux')
  assert.equal(profileWrites, 0, 'Unlocking, selecting and cancelling do not save changes')
  await page.setViewportSize({ width: 1440, height: 1000 })
  const editProfile = async (year, facultyName, beta = false) => {
    await page.locator('.sidebar-profile-trigger').click()
    await expect(page.locator('.academic-settings-card .academic-form')).toHaveCount(0)
    const writesBefore = profileWrites
    await page.getByRole('button', { name: 'Modifier mon parcours', exact: true }).click()
    await page.getByLabel(`${year}e année`).check()
    if (facultyName) {
      await page.locator('.academic-form').getByRole('combobox').fill(facultyName)
      await page.getByRole('option', { name: new RegExp(facultyName, 'i') }).click()
    }
    if (beta) await page.getByRole('checkbox', { name: /Je comprends/ }).check()
    await page.getByRole('button', { name: 'Vérifier les modifications' }).click()
    await expect(page.getByRole('group', { name: 'Confirmer le changement de parcours' })).toBeVisible()
    assert.equal(profileWrites, writesBefore, 'Review step does not update the academic profile')
    const saved = page.waitForResponse(response => response.url().includes('/api/onboarding/profile') && response.request().method() === 'PATCH' && response.ok())
    const confirmButton = page.getByRole('button', { name: 'Confirmer le changement', exact: true })
    await confirmButton.scrollIntoViewIfNeeded()
    await page.getByRole('heading', { name: 'Mon parcours de médecine', exact: true }).hover()
    assert.equal(await confirmButton.evaluate(el => getComputedStyle(el).backgroundColor), 'rgb(23, 101, 237)', 'Confirmation button is blue without hover')
    await confirmButton.click()
    const confirmation = page.getByRole('dialog', { name: 'Modifier ton parcours de médecine ?' })
    await expect(confirmation).toBeVisible()
    assert.equal(profileWrites, writesBefore, 'Opening the popup does not save changes')
    await confirmation.getByRole('button', { name: 'Annuler', exact: true }).click()
    await expect(confirmation).toHaveCount(0)
    assert.equal(profileWrites, writesBefore, 'Cancelling the popup does not save changes')
    await confirmButton.click()
    await expect(confirmation).toContainText('Nouveau parcours')
    await confirmation.getByRole('button', { name: 'Oui, modifier mon parcours', exact: true }).click()
    await saved
    await navigateItems()
  }
  await editProfile(5)
  await expect(programme).toContainText('Bordeaux · 5e année')
  await expect(programme.locator('.faculty-unit')).toHaveCount(20)
  await expect(programme).toContainText('Hématologie, Cancérologie, Médecine Palliative')
  await editProfile(5, 'Nice')
  await expect(programme.locator('.faculty-unit')).toHaveCount(13)
  await expect(programme).toContainText('Gériatrie')
  await programme.locator('.faculty-unit>summary').first().click()
  await expect(programme.locator('.faculty-unit-body').first()).toContainText('Aucun rattachement numéroté')
  await expect(programme.locator('.faculty-item-links')).toHaveCount(0)
  await editProfile(5, 'Rennes', true)
  await expect(programme).toContainText('programme détaillé 2026–2027 de cette année n’est pas encore documenté')
  await expect(programme.locator('.faculty-unit')).toHaveCount(0)
  await expect(programme).not.toContainText('Gériatrie')
  await expect(programme.locator('.faculty-source-candidates')).toHaveCount(0)
  assert.deepEqual(errors, [])
  console.log('Student programme: Bordeaux Y4/Y5, direct item links, Nice without inferred links, Rennes missing, responsive light/dark: passed.')
} finally {
  await browser.close()
  if (userId) await pool.query('DELETE FROM users WHERE id=$1', [userId])
  await pool.end()
}
