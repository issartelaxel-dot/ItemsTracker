// Explicit online smoke test for this isolated deployment; never targets production.
import fs from 'node:fs'
import assert from 'node:assert/strict'
import { chromium, expect } from '@playwright/test'
const access = JSON.parse(fs.readFileSync('.test-preview-release/access.json', 'utf8'))
assert.equal(new URL(access.url).hostname, 'test-itemstracker-20261015.167.233.129.21.sslip.io')
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = [], forbidden = []
  page.on('pageerror', e => errors.push(e.message))
  await page.route(/https:\/\/(api\.setup-hub\.com|[^/]*onrender\.com|n8n\.setup-hub\.com)\//, route => { forbidden.push(new URL(route.request().url()).hostname); return route.abort() })
  const anon = await page.request.get(access.url + 'api/state'); assert.equal(anon.status(), 401)
  await page.goto(access.url)
  await expect(page.getByRole('heading', { name: 'Découvre le nouvel ItemsTracker' })).toBeVisible()
  await page.getByLabel('Ton code d’accès').fill(access.code)
  await page.getByRole('button', { name: 'Accéder à la version de test', exact: true }).click()
  await page.getByRole('heading', { name: 'Personnalisons ton espace de révision' }).waitFor()
  assert.equal(await page.locator('.academic-year').count(), 3)
  await page.getByLabel('4e année').check()
  await page.getByRole('combobox').fill('dijon')
  await page.getByRole('option', { name: /Dijon/ }).click()
  await page.getByRole('button', { name: 'Afficher mes ressources', exact: true }).click()
  await page.getByRole('button', { name: 'Accéder au dashboard', exact: true }).click()
  await page.getByRole('heading', { name: /Bonjour/ }).waitFor()
  const me = await (await page.request.get(access.url + 'api/auth/me', { headers: { 'x-client-version': '0.1.1' } })).json()
  assert.equal(me.user.email, 'testeur@preview.invalid')
  await page.locator('.sidebar-nav').getByRole('button', { name: 'Items', exact: true }).click()
  await expect(page.locator('#items-section')).toBeVisible()
  await page.getByRole('button', { name: 'Matrice', exact: true }).click()
  await expect(page.locator('.items-matrix')).toBeVisible()
  await page.locator('.sidebar-profile-trigger').click()
  const avatar = page.locator('.settings-avatar-editor')
  await avatar.getByRole('button', { name: 'Initiales', exact: true }).click()
  await avatar.getByRole('button', { name: 'Personnalisé', exact: true }).click()
  await avatar.getByLabel('Initiales personnalisées', { exact: true }).fill('IT')
  await expect.poll(async () => (await (await page.request.get(access.url + 'api/state', { headers: { 'x-client-version': '0.1.1' } })).json()).state?.profile?.avatarCustomInitials, { timeout: 20000 }).toBe('IT')
  await page.reload()
  await page.locator('.sidebar-profile-trigger').click()
  await expect(avatar.locator('.settings-avatar-preview')).toContainText('IT')
  await avatar.getByRole('button', { name: 'Image', exact: true }).click()
  await expect(avatar.locator('.settings-avatar-dropzone')).toBeVisible()
  await page.locator('.settings-profile-editor').screenshot({ path: '.test-preview-release/settings-online.png' })
  await page.locator('.sidebar-nav').getByRole('button', { name: 'Calendrier', exact: true }).click()
  await page.getByRole('button', { name: 'Connecter Apple Calendrier', exact: true }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Créer ma connexion', exact: true }).click()
  const dialog = page.locator('.apple-setup-dialog')
  await expect(dialog.getByLabel('Mot de passe dédié', { exact: true })).not.toHaveValue('')
  const user = await dialog.getByLabel('Nom d’utilisateur', { exact: true }).inputValue(), password = await dialog.getByLabel('Mot de passe dédié', { exact: true }).inputValue()
  const dav = await page.request.fetch(access.url + 'dav/', { method: 'PROPFIND', headers: { Authorization: 'Basic ' + Buffer.from(user + ':' + password).toString('base64'), Depth: '0' } })
  assert.equal(dav.status(), 207, 'The test calendar has its own working CalDAV endpoint')
  await dialog.getByRole('button', { name: 'J’ai ajouté le compte dans Apple Calendrier', exact: true }).click()
  await dialog.getByRole('button', { name: 'Voir mes appareils', exact: true }).click()
  await dialog.getByRole('button', { name: 'Retirer', exact: true }).click()
  await dialog.getByRole('button', { name: 'Confirmer le retrait', exact: true }).click()
  await expect(dialog).toContainText('Aucun appareil connecté')
  await dialog.getByRole('button', { name: 'Fermer la connexion Apple Calendrier', exact: true }).click()
  for (const endpoint of ['api/auth/register/request', 'api/quiz/generate-mcq', 'api/admin/academic-catalog']) assert.equal((await page.request.post(access.url + endpoint)).status(), 403)
  await page.setViewportSize({ width: 390, height: 844 })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false)
  assert.deepEqual(errors, []); assert.deepEqual(forbidden, [])
  console.log('Online isolated preview: HTTPS, code-only access, onboarding, items/matrix, settings save/reload, CalDAV/device flow, blocked side effects and mobile: OK')
} finally { await browser.close() }
