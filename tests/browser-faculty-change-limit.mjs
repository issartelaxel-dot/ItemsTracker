import pg from 'pg'
import argon2 from 'argon2'
import assert from 'node:assert/strict'
import { chromium, expect } from '@playwright/test'
const pool = new pg.Pool({ connectionString: 'postgresql://postgres:local-preview-only@127.0.0.1:55432/postgres' })
let userId, browser
try {
  const email = `faculty-limit-${Date.now()}@local.test`
  userId = (await pool.query('INSERT INTO users(email,display_name,password_hash,created_at) VALUES($1,$2,$3,$4) RETURNING id', [email, 'Limite locale', await argon2.hash('Limits-Local-2026!'), new Date().toISOString()])).rows[0].id
  await pool.query("INSERT INTO academic_profiles(user_id,year_code,faculty_id,legacy_exempt,completed_at,faculty_change_count,faculty_choice_initialized) VALUES($1,'Y4','bordeaux',false,NOW(),2,true)", [userId])
  browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true })
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
  const page = await context.newPage()
  await page.goto('http://127.0.0.1:5173/itemstracker/onboarding-preview.html')
  await page.getByRole('textbox', { name: 'Adresse e-mail' }).fill(email)
  await page.getByRole('textbox', { name: 'Mot de passe' }).fill('Limits-Local-2026!')
  await page.getByRole('button', { name: 'Se connecter', exact: true }).click()
  await page.locator('.sidebar-profile-trigger').click()
  await expect(page.locator('.academic-settings-summary')).not.toContainText('disponible')
  await page.getByRole('button', { name: 'Modifier mon parcours', exact: true }).click()
  await expect(page.locator('.academic-change-limit')).toHaveCount(0)
  const blocked = await page.request.patch('http://127.0.0.1:5173/api/onboarding/profile', { data: { yearCode: 'Y4', facultyId: 'nice' }, headers: { 'X-Client-Version':'0.1.1' } })
  assert.equal(blocked.status(),409)
  assert.equal((await blocked.json()).code,'FACULTY_CHANGE_LIMIT')
  assert.equal((await page.request.get('http://127.0.0.1:5173/api/onboarding/admin/faculty-change-requests', { headers: { 'X-Client-Version':'0.1.1' } })).status(),403)
  await page.locator('.academic-form').getByRole('combobox').fill('Nice')
  await page.getByRole('option', { name: /Nice/ }).click()
  await page.getByRole('button', { name:'Vérifier les modifications' }).click()
  await expect(page.locator('.academic-change-limit')).toBeVisible()
  await page.getByLabel('Message facultatif').fill('Mutation universitaire pour ce test local')
  await page.getByRole('button', { name:'Envoyer la demande à l’administration' }).click()
  await expect(page.getByText('Demande envoyée à l’administration. Ton parcours actuel est conservé.')).toBeVisible()
  assert.equal((await pool.query('SELECT faculty_id FROM academic_profiles WHERE user_id=$1',[userId])).rows[0].faculty_id,'bordeaux')
  const adminContext = await browser.newContext({ viewport: { width:1440,height:1000 } })
  const admin = await adminContext.newPage()
  await admin.goto('http://127.0.0.1:5173/itemstracker/admin-app.html')
  await admin.getByLabel('Adresse e-mail').fill('hello@setup-hub.com')
  await admin.getByLabel('Mot de passe').fill('Admin-Local-2026!')
  await admin.getByRole('button',{name:'Se connecter',exact:true}).click()
  await admin.locator('.admin-sidebar').getByRole('button',{name:'Ressources',exact:true}).click()
  await admin.getByText('Demandes de changement de faculté',{exact:true}).click()
  const requests = admin.locator('.admin-availability-requests').filter({hasText:'Demandes de changement de faculté'})
  await requests.getByRole('button',{name:'Afficher les demandes',exact:true}).click()
  const row = requests.locator('li').filter({hasText:`Compte #${userId} ·`})
  await expect(row).toContainText('Mutation universitaire')
  await row.getByRole('button',{name:'Autoriser un changement supplémentaire'}).click()
  await expect(row).toContainText('Autorisée')
  assert.equal((await pool.query('SELECT faculty_id FROM academic_profiles WHERE user_id=$1',[userId])).rows[0].faculty_id,'bordeaux')
  await page.getByRole('button',{name:'Actualiser la réponse'}).click()
  await page.getByRole('button',{name:'Confirmer le changement',exact:true}).click()
  const popup = page.getByRole('dialog',{name:'Modifier ton parcours de médecine ?'})
  await expect(popup).toContainText('Il te restera 0 changement')
  await popup.getByRole('button',{name:'Oui, modifier mon parcours',exact:true}).click()
  await expect(page.locator('.academic-settings-summary')).toContainText('Nice')
  await expect(page.locator('.academic-settings-summary')).not.toContainText('disponible')
  assert.equal((await pool.query('SELECT faculty_change_count FROM academic_profiles WHERE user_id=$1',[userId])).rows[0].faculty_change_count,3)
  console.log('Faculty quota: server blocks bypass, admin endpoints forbid user, counters only at confirmation, request queue and admin UI approval, refresh and one extra confirmed change passed.')
} finally {
  await browser?.close()
  if (userId) await pool.query('DELETE FROM users WHERE id=$1',[userId])
  await pool.end()
}
