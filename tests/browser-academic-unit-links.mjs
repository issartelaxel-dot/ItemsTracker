import assert from 'node:assert/strict'
import { chromium, expect } from '@playwright/test'

const base = process.env.LOCAL_ACADEMIC_PREVIEW_URL || 'http://127.0.0.1:5173'
assert.ok(['127.0.0.1', 'localhost'].includes(new URL(base).hostname), 'This check is restricted to the local preview.')
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true })
const errors = []
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } })
  const page = await context.newPage()
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(`${base}/itemstracker/admin-app.html`)
  await page.getByLabel('Adresse e-mail').fill('hello@setup-hub.com')
  await page.getByLabel('Mot de passe').fill('Admin-Local-2026!')
  await page.getByRole('button', { name: 'Se connecter', exact: true }).click()
  await page.locator('.admin-sidebar').getByRole('button', { name: 'Ressources', exact: true }).click()
  await page.locator('.admin-availability-requests summary').click()
  await page.getByRole('button', { name: 'Afficher les demandes', exact: true }).click()
  await expect(page.locator('.admin-availability-requests')).toContainText('demande(s)')
  assert.equal(await page.locator('.admin-availability-requests [role="alert"]').count(), 0)
  await page.locator('.admin-availability-requests summary').click()
  const year = page.getByRole('combobox', { name: 'Année', exact: true })
  const faculty = page.getByRole('combobox', { name: 'Faculté', exact: true })
  const national = page.getByRole('combobox', { name: 'UE nationale', exact: true })
  const local = page.getByRole('combobox', { name: 'UE locale', exact: true })
  const chooseLocal = async label => {
    const option = local.locator('option').filter({ hasText: label })
    await expect(option).toHaveCount(1)
    await local.selectOption(await option.getAttribute('value'))
  }
  const links = page.getByRole('combobox', { name: 'Liens locaux', exact: true })
  const referenceBook = page.getByRole('combobox', { name: 'Ouvrage de référence', exact: true })
  const query = page.getByRole('searchbox')
  const items = page.locator('.admin-catalog-item')
  await expect(national).toBeVisible()
  await referenceBook.selectOption('cep-2026')
  await expect(items).toHaveCount(21)
  await expect(referenceBook.locator('option')).toHaveCount(7)
  await referenceBook.selectOption('couf-2025')
  await query.fill('#84')
  await expect(items).toHaveCount(1)
  await items.locator('.admin-catalog-reference-verified summary').click()
  await expect(items.locator('.admin-catalog-reference-verified')).toContainText('6e édition · 2025')
  await expect(items.locator('.admin-catalog-reference-verified a')).toHaveAttribute('href', /CH14_.*#page=1$/)
  await referenceBook.selectOption('cemir-2024')
  await query.fill('#325')
  await expect(items).toHaveCount(0)
  await referenceBook.selectOption('cnpm-cnet-2024')
  await query.fill('#329')
  await expect(items).toHaveCount(1)
  await items.locator('.admin-catalog-reference-verified summary').click()
  await expect(items.locator('.admin-catalog-reference-verified li')).toHaveCount(3)
  await expect(items.locator('.admin-catalog-reference-verified')).toContainText('© 2020 · fichier MAJ2024')
  await items.locator('.admin-catalog-reference-candidate summary').click()
  await expect(items.locator('.admin-catalog-reference-candidate li')).toHaveCount(2)
  await page.screenshot({ path: '/tmp/itemstracker-reference-books-desktop.png', fullPage: false })
  await query.fill('')
  await referenceBook.selectOption('')
  await national.selectOption('10')
  await expect(items).toHaveCount(10)
  await expect(page.locator('.admin-catalog-national-unit')).toHaveCount(10)
  assert.equal(await items.first().locator('strong').first().textContent(), '#321')
  await year.selectOption('Y5')
  await expect(national).toHaveValue('')
  await chooseLocal('Éthique à l’EDN')
  await expect(items).toHaveCount(14)
  await expect(page.locator('.admin-catalog-unit')).toHaveCount(1)
  await page.locator('.admin-catalog-unit-items summary').click()
  await expect(page.locator('.admin-catalog-unit-item')).toHaveCount(14)
  assert.match(await page.locator('.admin-catalog-unit-item a').first().getAttribute('href'), /#page=60$/)
  assert.equal(await items.first().locator('.admin-catalog-local-link').filter({ hasText: 'Éthique à l’EDN' }).count(), 1)
  await page.screenshot({ path: '/tmp/itemstracker-ue-links-desktop.png', fullPage: true })
  await chooseLocal('Sensibilisation à l’hypnose médicale')
  await expect(items).toHaveCount(1)
  await expect(items.first()).toContainText('Référence locale citée')
  await faculty.selectOption('nice')
  await expect(local).toHaveValue('')
  await expect(page.locator('.admin-catalog-summary')).toContainText('0 items avec un lien local documenté')
  await links.selectOption('linked')
  await expect(items).toHaveCount(0)
  await links.selectOption('unlinked')
  await national.selectOption('11')
  await expect(items).toHaveCount(37)
  await expect(items.last()).toContainText('#367')
  await faculty.selectOption('bordeaux')
  await year.selectOption('Y4')
  await chooseLocal('Médecine légale')
  await expect(page.locator('.admin-catalog-mapping-issue')).toHaveCount(1)
  await expect(items).toHaveCount(0)
  await page.locator('.admin-catalog-mapping-issue summary').click()
  await expect(page.locator('.admin-catalog-mapping-issue')).toContainText('discriminations')
  await expect(page.locator('.admin-catalog-mapping-issue a')).toHaveAttribute('href', /#page=57$/)
  await local.selectOption('')
  for (const width of [360, 390, 430, 768, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `Overflow at ${width}px`)
  }
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: '/tmp/itemstracker-ue-links-mobile.png', fullPage: false })
  await page.evaluate(() => { document.documentElement.dataset.theme = 'dark' })
  await page.screenshot({ path: '/tmp/itemstracker-ue-links-mobile-dark.png', fullPage: false })
  assert.deepEqual(errors, [])
  console.log('Academic unit filters, faculty/year separation, optional references, numbering conflicts, and five viewport widths: passed.')
} finally {
  await browser.close()
}
