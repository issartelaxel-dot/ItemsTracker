function program(facultyId, yearCode, sourceUrl, rows, extra = {}) {
  return {
    facultyId, yearCode, academicTerm: '2026-2027', sourceUrl,
    sourcePages: [...new Set(rows.map(row => row[2]))],
    reviewStatus: 'extracted_needs_review', ...extra,
    units: rows.map(([code, label, page, kind = 'obligatoire', slot = '']) => ({
      code, label, page, kind, ...(slot ? { slot } : {}),
      itemNumbers: [], itemReferences: [],
    })),
  }
}

