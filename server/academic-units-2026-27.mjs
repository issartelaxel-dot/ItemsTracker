function makeProgram(facultyId, yearCode, sourceUrl, pages, entries) {
  return {
    facultyId, yearCode, academicTerm: '2026-2027', sourceUrl, sourcePages: pages,
    reviewStatus: 'extracted_needs_review',
    units: entries.map(([code, label, page, itemReferences = [], meta = {}]) => ({
      code, label, page, ...meta, itemNumbers: itemReferences.map(reference => reference[0]),
      itemReferences: itemReferences.map(([number, sourcePage]) => ({ number, page: sourcePage })),
    })),
  }
}

